class ReadingController:
    @staticmethod
    async def _questions(session: AsyncSession, passage_id: str) -> list[Question]:
        rows = await session.scalars(
            select(Question)
            .where(Question.passage_id == passage_id)
            .order_by(Question.order_index)
        )
        return list(rows)

    @classmethod
    async def get_passage(
        cls,
        session: AsyncSession,
        user_id: str,
        difficulty: str | None,
        exam_type: str,
    ) -> PassageResponse:
        await _ensure_seeded(session)
        if difficulty is None or difficulty == "adaptive":
            difficulty, _, _ = await resolve_difficulty(session, user_id, "reading")
        # Random pick so repeated practice varies the content.
        passage = await session.scalar(
            select(Passage)
            .where(Passage.exam_type == exam_type, Passage.difficulty == difficulty)
            .order_by(func.random())
            .limit(1)
        )
        if passage is None:
            passage = await session.scalar(
                select(Passage)
                .where(Passage.exam_type == exam_type)
                .order_by(func.random())
                .limit(1)
            )
        if passage is None:
            passage = await session.scalar(
                select(Passage).order_by(func.random()).limit(1)
            )
        if passage is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND, detail="No passages available"
            )
        questions = await cls._questions(session, passage.id)
        return PassageResponse(
            id=passage.id,
            title=passage.title,
            body=passage.body,
            exam_type=passage.exam_type,
            difficulty=passage.difficulty,
            topic=passage.topic,
            word_count=passage.word_count,
            questions=[
                QuestionPublic(
                    id=q.id,
                    type=q.type,
                    prompt=q.prompt,
                    options=q.options,
                )
                for q in questions
            ],
        )

    @classmethod
    async def _grade(
        cls, questions: list[Question], answers: dict[str, Any]
    ) -> tuple[int, list[PerQuestionResult]]:
        raw = 0
        per_question: list[PerQuestionResult] = []
        for q in questions:
            submitted = answers.get(q.id)
            correct = is_correct(submitted, q.correct_answer)
            if correct:
                raw += 1
            per_question.append(
                PerQuestionResult(
                    question_id=q.id,
                    type=q.type,
                    correct=correct,
                    submitted=submitted,
                    correct_answer=q.correct_answer,
                    explanation=q.explanation,
                )
            )
        return raw, per_question

    @classmethod
    async def submit(
        cls, session: AsyncSession, user: User, payload: ReadingSubmitRequest
    ) -> ReadingResultResponse:
        passage = await session.get(Passage, payload.passage_id)
        if passage is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND, detail="Passage not found"
            )
        questions = await cls._questions(session, passage.id)
        total = len(questions)
        raw, per_question = await cls._grade(questions, payload.answers)
        band = reading_band(raw, total, passage.exam_type)

        attempt = ReadingAttempt(
            user_id=user.id,
            passage_id=passage.id,
            answers=payload.answers,
            raw_score=raw,
            total_questions=total,
            band=band,
        )
        session.add(attempt)
        wrong_tags = list(
            dict.fromkeys(pq.type for pq in per_question if not pq.correct)
        )
        if wrong_tags:
            await WeaknessService.record(session, user.id, "reading", wrong_tags)
        await session.flush()
        return ReadingResultResponse(
            attempt_id=attempt.id,
            passage_id=passage.id,
            raw_score=raw,
            total_questions=total,
            band=band,
            per_question=per_question,
        )

    @classmethod
    async def get_attempt(
        cls, session: AsyncSession, user: User, attempt_id: str
    ) -> ReadingResultResponse:
        attempt = await _attempts.get_owned(session, attempt_id, user.id)
        questions = await cls._questions(session, attempt.passage_id)
        _, per_question = await cls._grade(questions, attempt.answers)
        return ReadingResultResponse(
            attempt_id=attempt.id,
            passage_id=attempt.passage_id,
            raw_score=attempt.raw_score,
            total_questions=attempt.total_questions,
            band=attempt.band,
            per_question=per_question,
        )
