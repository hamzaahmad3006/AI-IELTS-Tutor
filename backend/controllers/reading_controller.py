#: Ownership-checked reads. Returns 404 rather than 403 for someone
#: else's row, so an id cannot be confirmed by a stranger.
_attempts = OwnedRepository(ReadingAttempt, label="Attempt")


# ---------- Schemas ----------
class QuestionPublic(CamelModel):
    id: str
    type: str
    prompt: str
    options: list[str] | None = None


class PassageResponse(CamelModel):
    id: str
    title: str
    body: str
    exam_type: str
    difficulty: str
    topic: str | None
    word_count: int
    questions: list[QuestionPublic]


class ReadingSubmitRequest(CamelModel):
    passage_id: str
    answers: dict[str, Any]


class PerQuestionResult(CamelModel):
    question_id: str
    type: str
    correct: bool
    submitted: Any
    correct_answer: Any
    explanation: str | None


class ReadingResultResponse(CamelModel):
    attempt_id: str
    passage_id: str
    raw_score: int
    total_questions: int
    band: float
    per_question: list[PerQuestionResult]


